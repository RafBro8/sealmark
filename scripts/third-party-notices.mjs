/**
 * Writes THIRD-PARTY-NOTICES.md from the packages actually installed.
 *
 * Sealmark is sold as paid integration work, and every library it ships is MIT,
 * Apache-2.0 or BSD — all of which allow that, provided their notices travel with
 * the product. Generated rather than hand-written so it cannot fall behind the
 * dependencies.
 *
 * Run: node scripts/third-party-notices.mjs
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url);
const rootDir = root.pathname.replace(/^\/([A-Za-z]:)/, '$1');

const LICENCE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENCE.md', 'license', 'license.md'];

/**
 * Every runtime dependency, read from the lockfile.
 *
 * The lockfile is the same source npm installs from, and it already marks the
 * packages that only exist for development. Reading it beats shelling out to
 * `npm ls`: no child process, and Node on Windows refuses to spawn npm's .cmd
 * wrapper directly.
 */
function runtimeDependencies() {
  const lock = JSON.parse(readFileSync(join(rootDir, 'package-lock.json'), 'utf8'));
  if (lock.lockfileVersion < 2) {
    throw new Error(`package-lock.json is version ${lock.lockfileVersion}; this needs 2 or later`);
  }

  const found = new Map();
  for (const [path, info] of Object.entries(lock.packages ?? {})) {
    // The root project and its workspaces are not third-party; neither are
    // dev-only tools or workspace links, which never reach a build. Optional
    // packages are skipped too: the only ones here are pdf.js's native canvas
    // backend, which is for rendering under Node and is never bundled. npm
    // installs a different one of those per platform, so including them would
    // make this file depend on the machine that generated it.
    if (!path.includes('node_modules/') || info.dev || info.link || info.optional) continue;
    const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    if (name.startsWith('@sealmark/') || !info.version || found.has(name)) continue;
    found.set(name, info.version);
  }
  return [...found].sort(([a], [b]) => a.localeCompare(b));
}

function licenceFor(name) {
  const dir = join(rootDir, 'node_modules', ...name.split('/'));
  if (!existsSync(dir)) return null;
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const file = LICENCE_FILES.find((candidate) => existsSync(join(dir, candidate)));
  return {
    licence: typeof manifest.license === 'string' ? manifest.license : (manifest.license?.type ?? 'see text below'),
    text: file ? readFileSync(join(dir, file), 'utf8').trim() : null,
    homepage: manifest.homepage ?? manifest.repository?.url ?? '',
  };
}

const packages = runtimeDependencies();
const lines = [
  '# Third-party notices',
  '',
  'Sealmark includes the software and fonts listed here. Each is used under its own',
  "licence, reproduced in full below. This file is generated by",
  '`node scripts/third-party-notices.mjs` and must be delivered with any build of',
  'Sealmark, including integrations installed on a client site.',
  '',
  '## Software',
  '',
  '| Package | Version | Licence |',
  '| --- | --- | --- |',
];

const details = [];
for (const [name, version] of packages) {
  const info = licenceFor(name);
  // A shipped package must never drop out of the notices quietly.
  if (!info) throw new Error(`${name} is a runtime dependency but is not installed — run npm install`);
  lines.push(`| ${name} | ${version} | ${info.licence} |`);
  if (info.text) {
    details.push(`### ${name} ${version}\n\n${info.homepage ? `${info.homepage}\n\n` : ''}\`\`\`\n${info.text}\n\`\`\``);
  }
}

// Fonts ship as files rather than packages, with their licences alongside them.
const assets = join(rootDir, 'packages', 'core', 'assets');
const fontLicences = readdirSync(assets).filter((file) => file.endsWith('.txt'));
lines.push('', '## Fonts', '', '| Font | Licence | Notes |', '| --- | --- | --- |');
for (const file of fontLicences) {
  const font = file.replace(/-(OFL|LICENSE)\.txt$/, '');
  const apache = file.endsWith('LICENSE.txt');
  // Nothing is modified any more, so every font keeps its name cleanly.
  const note = 'Shipped as published';
  lines.push(`| ${font} | ${apache ? 'Apache-2.0' : 'SIL Open Font License 1.1'} | ${note} |`);
}
lines.push('', 'The full text of each font licence is in `packages/core/assets/`.', '');
lines.push('## Licence texts', '', details.join('\n\n'), '');

writeFileSync(join(rootDir, 'THIRD-PARTY-NOTICES.md'), lines.join('\n'));
console.log(`THIRD-PARTY-NOTICES.md: ${packages.length} packages, ${fontLicences.length} fonts`);
